import { readdir, stat, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

// Build the video-discipline project data from plain folders, so new work never
// requires touching a component. Expected layout:
//
//   public/assets/works/<category>/<project-folder>/
//     meta.json            (optional: { title, description, year, tools, brand })
//     cover.jpg            (optional; falls back to the first image found)
//     film.mp4             (first video in the folder becomes the main media)
//     characters/          ← 人物资产 (three-views, portraits, expressions)
//     environments/        ← 场景资产
//     props/               ← 道具资产
//
//   node scripts/sync-films.mjs
const VIDEO_CATEGORIES = ['short-film', 'comic-drama', 'tvc', 'ai-live-action', 'game'];
const VIDEO_EXT = /\.(mp4|webm|mov|m4v)$/i;
const IMAGE_EXT = /\.(png|jpe?g|webp|avif)$/i;
const ASSET_KEYS = { characters: 'characters', environments: 'environments', props: 'props' };

const walk = async dir => {
  const out = [];
  let entries;
  try { entries = await readdir(dir, { withFileTypes: true }); } catch { return out; }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full));
    else out.push(full);
  }
  return out;
};

const listImages = async dir => {
  let entries;
  try { entries = await readdir(dir, { withFileTypes: true }); } catch { return []; }
  return entries
    .filter(entry => entry.isFile() && IMAGE_EXT.test(entry.name))
    .map(entry => entry.name)
    .sort((a, b) => a.localeCompare(b, 'zh-Hans-CN', { numeric: true, sensitivity: 'base' }));
};

const publicURL = (categoryDir, ...segments) =>
  `/assets/works/${categoryDir}/` + segments.map(encodeURIComponent).join('/');

const films = {};

for (const category of VIDEO_CATEGORIES) {
  const categoryDir = path.resolve(`public/assets/works/${category}`);
  await mkdir(categoryDir, { recursive: true });
  const records = [];
  let entries;
  try { entries = await readdir(categoryDir, { withFileTypes: true }); } catch { entries = []; }

  for (const entry of entries.filter(e => e.isDirectory() && !/^[._]/.test(e.name)).sort((a, b) => a.name.localeCompare(b.name, 'zh-Hans-CN', { numeric: true }))) {
    const projectDir = path.join(categoryDir, entry.name);
    const files = await walk(projectDir);

    let meta = {};
    try { meta = JSON.parse(await readFile(path.join(projectDir, 'meta.json'), 'utf8')); } catch {}

    const topImages = (await listImages(projectDir)).filter(name => !/^cover\./i.test(name));
    const video = files.find(file => VIDEO_EXT.test(file));
    const coverFile = (await listImages(projectDir)).find(name => /^cover\./i.test(name)) || topImages[0] || '';

    const assets = {};
    for (const [key, folder] of Object.entries(ASSET_KEYS)) {
      let candidates;
      try { candidates = await readdir(path.join(projectDir, folder), { withFileTypes: true }); } catch { candidates = []; }
      const dirName = candidates.find(c => c.isDirectory() && c.name.toLowerCase() === folder)?.name || folder;
      const names = await listImages(path.join(projectDir, dirName));
      assets[key] = names.map(name => ({ src: publicURL(category, entry.name, dirName, name), caption: path.parse(name).name }));
    }

    const gallery = topImages.slice(1).map(name => ({ src: publicURL(category, entry.name, name), caption: '' }));

    records.push({
      id: `${category}-` + createHash('sha256').update(entry.name).digest('hex').slice(0, 12),
      title: String(meta.title || entry.name),
      category,
      year: meta.year ?? null,
      description: String(meta.description || ''),
      brand: meta.brand ? String(meta.brand) : '',
      duration: meta.duration ? String(meta.duration) : '',
      episode: meta.episode ? String(meta.episode) : '',
      cover: coverFile ? publicURL(category, entry.name, coverFile) : '',
      mediaType: 'video',
      media: video ? publicURL(category, ...path.relative(categoryDir, video).split(path.sep)) : '',
      poster: coverFile ? publicURL(category, entry.name, coverFile) : '',
      gallery,
      tools: Array.isArray(meta.tools) ? meta.tools.map(String) : [],
      assets,
      sourceFolder: entry.name
    });
  }
  if (records.length) films[category] = records;
}

await writeFile(
  'src/data/films.js',
  '// Generated by node scripts/sync-films.mjs; original files remain unchanged.\n' +
  'export const films = ' + JSON.stringify(films, null, 2) + ';\n'
);

const total = Object.values(films).reduce((sum, list) => sum + list.length, 0);
console.log(`Indexed ${total} video project${total === 1 ? '' : 's'} across ${Object.keys(films).length} discipline${Object.keys(films).length === 1 ? '' : 's'}.`);
