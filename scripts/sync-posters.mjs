import { readdir, copyFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

// Mirror a source folder into public/assets/works/<category>/ and rebuild that
// category's data file from whatever currently lives in public/. Re-running with
// a different folder keeps every previously indexed image.
//
//   node scripts/sync-posters.mjs <folder>                      -> poster
//   node scripts/sync-posters.mjs <folder> --category=banner    -> banner
//   node scripts/sync-posters.mjs                               -> rebuild poster index only
//
// Image carousels: poster / banner. IP uses a curated character/scene index.
// Video categories keep their own
// hand-written records in src/data/works.js because they carry assets and links.
const TARGETS = {
  poster: { dir: 'poster', file: 'src/data/posters.js', export: 'posters' },
  banner: { dir: 'banner', file: 'src/data/banners.js', export: 'banners' }
};

const args = process.argv.slice(2);
const flag = args.find(arg => arg.startsWith('--category='));
const sourceArg = args.find(arg => !arg.startsWith('--'));
const categoryId = (flag ? flag.split('=')[1] : 'poster').trim();
const target = TARGETS[categoryId];

if (!target) {
  if(categoryId==='ip')console.error('IP 使用 src/data/ips.js 的角色/场景对应表；通用轮播同步不能覆盖它。');
  console.error(`Unknown category "${categoryId}". Available: ${Object.keys(TARGETS).join(', ')}`);
  process.exit(1);
}

const destination = path.resolve(`public/assets/works/${target.dir}`);
await mkdir(destination, { recursive: true });

if (sourceArg) {
  const source = path.resolve(sourceArg);
  for (const file of await readdir(source)) {
    if (!/\.(png|jpe?g|webp|avif)$/i.test(file)) continue;
    await copyFile(path.join(source, file), path.join(destination, file));
  }
}

const fileList = (await readdir(destination))
  .filter(name => /\.(png|jpe?g|webp|avif)$/i.test(name))
  .filter(name => name !== '.gitkeep')
  .sort((a, b) => a.localeCompare(b, 'zh-Hans-CN', { numeric: true, sensitivity: 'base' }));

// Derive a short work label. Timestamped filenames (ChatGPT downloads, camera
// exports, ISO dates) carry no real title, and the site must not display any
// dates — so they fall back to a numbered label instead of a date string.
const CATEGORY_LABELS = { poster: '海报', banner: 'Banner', ip: 'IP' };
function deriveTitle(file, index) {
  const stem = categoryId==='banner' ? path.parse(file).name.replace(/^\d{4}(?:年)?(?=[^\d])/,'') : path.parse(file).name;
  const padded = String(index + 1).padStart(2, '0');
  const label = CATEGORY_LABELS[categoryId] || categoryId;
  const timestamped = /^(?:ChatGPT[ _-]*(?:图像|图片|Image))?[\s]*(?:\d{4})[-./年]/i.test(stem)
    || /^\d{4}[-./](\d{1,2})[-./](\d{1,2})[ T_-]+/i.test(stem);
  if (timestamped) return `${label} · ${padded}`;
  return stem.length > 36 ? `${label} · ${padded}` : stem;
}

const records = fileList.map((file, index) => ({
  id: `${categoryId}-` + createHash('sha256').update(file).digest('hex').slice(0, 12),
  title: deriveTitle(file, index),
  category: categoryId,
  year: null,
  description: '',
  cover: `/assets/works/${target.dir}/` + encodeURIComponent(file),
  mediaType: 'image',
  media: `/assets/works/${target.dir}/` + encodeURIComponent(file),
  gallery: [],
  tools: [],
  sourceFile: file
}));

await writeFile(
  target.file,
  `// Generated by node scripts/sync-posters.mjs --category=${categoryId}; original files remain unchanged.\n` +
  `export const ${target.export} = ` + JSON.stringify(records, null, 2) + ';\n'
);
console.log(`Indexed ${records.length} ${categoryId} image${records.length === 1 ? '' : 's'} into ${target.file}.`);
